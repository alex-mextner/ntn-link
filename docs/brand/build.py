# /// script
# requires-python = ">=3.11"
# dependencies = ["potracer", "pillow", "numpy"]
# ///
"""
Rebuilds every brand asset from docs/brand/fastp-logo-original.png (sha256 in the .sha256 file):

    uv run docs/brand/build.py

1. Traces the PNG (ink = darkness over white, so the transparent margin and the off-white page
   interior both count as paper) with potrace into one single-colour path.
2. Writes docs/brand/fastp-logo.svg (`currentColor`), packages/core/src/brand.ts (the same
   path for the web header, the card and the stub pages), and the favicon SVG.
3. Rasterises the icon tiles (favicon.ico, 16/32/512 PNG, 180 apple-touch, extension 16/32/48/128)
   with headless Chrome and records how far the SVG is from the original at 512 px.

Nothing here runs in the product: the generated files are committed.
"""
import hashlib, io, json, shutil, subprocess, sys, tempfile
from pathlib import Path

import numpy as np
import potrace
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
BRAND = ROOT / "docs/brand"
ORIGINAL = BRAND / "fastp-logo-original.png"
EXPECTED_SHA = (BRAND / "fastp-logo-original.png.sha256").read_text().split()[0]
INK = "#0b0b14"
PAPER = "#ffffff"
PAD = 0.04  # share of the square viewBox left empty around the drawing

assert hashlib.sha256(ORIGINAL.read_bytes()).hexdigest() == EXPECTED_SHA, "original logo changed"

rgba = Image.open(ORIGINAL).convert("RGBA")
flat = Image.alpha_composite(Image.new("RGBA", rgba.size, (255, 255, 255, 255)), rgba).convert("L")
ink = np.array(flat) < 128
ys, xs = np.where(ink)
x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
side = round(max(x1 - x0, y1 - y0) * (1 + 2 * PAD))
vx, vy = round((x0 + x1) / 2 - side / 2), round((y0 + y1) / 2 - side / 2)
VIEWBOX = f"{vx} {vy} {side} {side}"


def contours(items):
    for item in items:
        yield item
        yield from contours(item.children or [])


# potracer inverts its input: True means paper.
traced = potrace.Bitmap(~ink).trace(turdsize=40, alphamax=1.0, opticurve=True, opttolerance=1.0)
curves = list(contours(traced))


def corner_commands(cx: int, cy: int, ints: list) -> tuple[str, int, int]:
    """A potrace corner is two straight lines: to the vertex, then to the end point."""
    (ax, ay), (bx, by) = ints
    return f"l{ax - cx} {ay - cy}l{bx - ax} {by - ay}", bx, by


def curve_commands(cx: int, cy: int, ints: list) -> tuple[str, int, int]:
    parts = [str(v) for px, py in ints for v in (px - cx, py - cy)]
    return "c" + " ".join(parts), ints[-1][0], ints[-1][1]


def contour_commands(c) -> str:
    cx, cy = round(c.start_point.x), round(c.start_point.y)
    out = [f"M{cx} {cy}"]
    for seg in c.segments:
        pts = [seg.c, seg.end_point] if seg.is_corner else [seg.c1, seg.c2, seg.end_point]
        ints = [(round(p.x), round(p.y)) for p in pts]
        text, cx, cy = (corner_commands if seg.is_corner else curve_commands)(cx, cy, ints)
        out.append(text)
    out.append("z")
    return "".join(out)


def path_data() -> str:
    """Absolute potrace curves, rounded to integers and written as relative commands."""
    return "".join(contour_commands(c) for c in curves).replace(" -", "-")


D = path_data()
svg = lambda attrs, body: f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{VIEWBOX}"{attrs}>{body}</svg>'
PATH = f'<path fill-rule="evenodd" d="{D}"/>'
# Ink on a light tab, light on a dark one: `prefers-color-scheme` follows the browser theme for tab icons.
FAVICON_STYLE = f"<style>path{{fill:{INK}}}@media(prefers-color-scheme:dark){{path{{fill:#f3f3f8}}}}</style>"

(BRAND / "fastp-logo.svg").write_text(svg(' fill="currentColor"', PATH) + "\n")
(ROOT / "packages/core/src/brand.ts").write_text(
    f"""/**
 * The fastp.ge logo as one single-colour path (generated by docs/brand/build.py from the
 * owner's PNG; do not edit by hand). Callers set the colour with `fill`.
 */
export const LOGO_VIEWBOX = '{VIEWBOX}';
export const LOGO_PATH = '{D}';
/** Stroke added in viewBox units where the logo is drawn at 40-56 px: the hand-drawn hairline stays crisp. */
export const LOGO_STROKE = 16;

/**
 * The logo for a browser tab: ink on a light tab, light on a dark one, transparent background.
 */
export const FAVICON_SVG =
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${{LOGO_VIEWBOX}}">{FAVICON_STYLE}<path fill-rule="evenodd" d="${{LOGO_PATH}}"/></svg>`;
"""
)
favicon_svg = svg("", f"{FAVICON_STYLE}{PATH}")
(ROOT / "apps/web/app/icon.svg").write_text(favicon_svg + "\n")

chrome = shutil.which("google-chrome") or shutil.which("chromium")
assert chrome, "headless Chrome is needed to rasterise"
WORK = Path(tempfile.mkdtemp(prefix="fastp-brand-"))


def render(html: str, name: str, px: int = 1024) -> Image.Image:
    page = WORK / f"{name}.html"
    page.write_text(f'<body style="margin:0;background:transparent">{html}</body>')
    out = WORK / f"{name}.png"
    subprocess.run(
        [chrome, "--headless=new", "--no-sandbox", "--hide-scrollbars", "--default-background-color=00000000",
         f"--screenshot={out}", f"--window-size={px},{px}", page.as_uri()],
        check=True, capture_output=True,
    )
    return Image.open(out).convert("RGBA")


def tile(rx: float, pad: float, bold: int = 0) -> Image.Image:
    """
    The logo on a light tile (rx and pad as shares of the tile): legible on any toolbar.
    `bold` thickens the strokes by that many viewBox units, for sizes where a hairline of the
    hand-drawn line would blur to grey.
    """
    inner = 1 - 2 * pad
    ring = f'<rect width="1024" height="1024" rx="{rx * 1024}" fill="{PAPER}"/>'
    logo = f'<svg x="{pad * 1024}" y="{pad * 1024}" width="{inner * 1024}" height="{inner * 1024}" viewBox="{VIEWBOX}" fill="{INK}" stroke="{INK}" stroke-width="{bold}" stroke-linejoin="round">{PATH}</svg>'
    html = f'<svg width="1024" height="1024" xmlns="http://www.w3.org/2000/svg">{ring}{logo}</svg>'
    return render(html, f"tile-{rx}-{pad}-{bold}")


def png_bytes(image: Image.Image) -> bytes:
    buffer = io.BytesIO()
    image.save(buffer, "PNG", optimize=True)
    return buffer.getvalue()


def sized(image: Image.Image, px: int) -> Image.Image:
    return image.resize((px, px), Image.LANCZOS)


# Stroke weight and padding per size: small icons get a heavier line and a bigger drawing.
LARGE = tile(0.22, 0.09)
SMALL = {16: tile(0.2, 0.05, 34), 32: tile(0.22, 0.06, 18), 48: tile(0.22, 0.07, 8)}
apple = tile(0, 0.13)
app = ROOT / "apps/web/app"
# Next.js file conventions: icon1/icon2/icon3 are extra <link rel="icon"> entries with their sizes.
(app / "icon1.png").write_bytes(png_bytes(sized(SMALL[16], 16)))
(app / "icon2.png").write_bytes(png_bytes(sized(SMALL[32], 32)))
(app / "icon3.png").write_bytes(png_bytes(sized(LARGE, 512)))
(app / "apple-icon.png").write_bytes(png_bytes(sized(apple.convert("RGB"), 180)))
frames = [sized(SMALL[px], px) for px in (16, 32, 48)]
frames[2].save(app / "favicon.ico", sizes=[(16, 16), (32, 32), (48, 48)], append_images=frames[:2])
for px, image in {16: SMALL[16], 32: SMALL[32], 48: SMALL[48], 128: LARGE}.items():
    (ROOT / f"extension/static/icons/{px}.png").write_bytes(png_bytes(sized(image, px)))

# How far the SVG is from the original at 512 px, drawn from the same square viewBox.
crop = flat.crop((vx, vy, vx + side, vy + side)).resize((512, 512), Image.LANCZOS)
mine = render(f'<svg width="512" height="512" xmlns="http://www.w3.org/2000/svg" viewBox="{VIEWBOX}">{PATH}</svg>', "cmp", 512)
mine_ink = np.array(Image.alpha_composite(Image.new("RGBA", mine.size, (255, 255, 255, 255)), mine).convert("L")) < 128
orig_ink = np.array(crop) < 128
union = (mine_ink | orig_ink).sum()
report = {
    "viewBox": VIEWBOX,
    "pathBytes": len(D),
    "contours": len(curves),
    "inkPixelsOriginal512": int(orig_ink.sum()),
    "inkPixelsSvg512": int(mine_ink.sum()),
    "differingPixels512": int((mine_ink ^ orig_ink).sum()),
    "iou512": round(float((mine_ink & orig_ink).sum() / union), 4),
}
print(json.dumps(report, indent=2))
overlay = np.full((512, 512, 3), 255, np.uint8)
overlay[orig_ink & ~mine_ink] = (255, 0, 0)
overlay[mine_ink & ~orig_ink] = (0, 90, 255)
overlay[mine_ink & orig_ink] = (40, 40, 40)
Image.fromarray(overlay).save(WORK / "overlay.png")
print("scratch:", WORK)
